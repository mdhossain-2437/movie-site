/**
 * DEVELOPMENT FIXTURES — never rendered in staging or production (see ./stage.ts).
 *
 * Records describe real early films with factual metadata so the interface can be designed
 * against honest content. Their public-domain status has NOT been verified by legal review:
 * every title stays unpublished, and each carries only a PENDING rights request with no
 * evidence attached. No rights approval is seeded. Synopses are original editorial copy and
 * all artwork is generated in code (components/art/key-art.tsx); no third-party posters.
 */
export const FIXTURE_SNAPSHOT_AT = new Date("2026-11-06T00:00:00.000Z");
const REQUEST_WINDOW_END = new Date("2031-11-06T00:00:00.000Z");

function pendingRightsRequest(titleId: string): RightsGrantRecord {
  return {
    id: `grant_${titleId}`,
    titleId,
    assetId: null,
    status: "PENDING",
    // Requested capabilities only. DOWNLOAD is deliberately not requested: STREAM never implies it.
    allowedActions: ["METADATA", "ARTWORK", "STREAM"],
    allowedTerritories: ["BD"],
    validFrom: FIXTURE_SNAPSHOT_AT,
    validUntil: REQUEST_WINDOW_END,
    requiredEntitlement: "FREE",
    maxResolution: "1080p",
    requiresDrm: false,
    attributionText: null,
    evidence: [],
  };
}

interface TitleSeed {
  slug: string;
  title: string;
  titleBn: string;
  originalTitle: string;
  originalLanguage: string;
  soundFormat: string;
  year: number;
  runtimeMinutes: number;
  countries: string[];
  studio: string;
  genres: string[];
  synopsis: string;
  synopsisBn?: string;
  credits: FixtureCredit[];
  art: ArtSpec;
}

function defineTitle(seed: TitleSeed): CatalogueTitle {
  const id = `title_fx_${seed.slug.replace(/-/g, "_")}`;
  return {
    ...seed,
    id,
    synopsisBn: seed.synopsisBn ?? null,
    maturityRating: "UNRATED",
    status: "IN_REVIEW",
    isDevelopmentFixture: true,
    rightsClaim: "PUBLIC_DOMAIN_CLAIM_UNVERIFIED",
    artworkProvenance: GENERATED_ART_PROVENANCE,
    grants: [pendingRightsRequest(id)],
  };
}

const director = (person: string): FixtureCredit => ({ department: "DIRECTOR", person });
const writer = (personOrName: { person?: string; name?: string }): FixtureCredit => ({
  department: "WRITER",
  ...personOrName,
});
const actor = (ref: { person?: string; name?: string }, character?: string): FixtureCredit => ({
  department: "ACTOR",
  ...ref,
  character,
});

